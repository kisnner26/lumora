import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
const R = {}, context = vm.createContext({ window: { RISO: R } });
vm.runInContext(readFileSync(new URL('../js/riso/riso-relato.js', import.meta.url), 'utf8'), context);
const lines = ['I wait for you at home', 'The light is fading', 'Goodbye, I am leaving you', 'I walk down the street', 'I wait for you at home', 'Come back and hold my hand', 'We start again'].map((text, i) => ({ text, t: i * 5 }));
const a = R.narrative.plan(lines);
assert.equal(a[0].action, 'wait'); assert.equal(a[0].cast, 2);
assert.equal(a[1].place, 'cuarto'); assert.equal(a[1].motif, 'banco_vacio');
assert.equal(a[2].action, 'leave'); assert.equal(a[3].place, 'ciudad');
assert.equal(a[4].visualChapter, a[0].visualChapter); assert.equal(a[4].reprise, true); assert.equal(a[4].place, a[0].place); assert.equal(a[4].motif, a[0].motif);
assert.equal(a[5].action, 'return'); assert.equal(a[6].action, 'grow');
assert.equal(JSON.stringify(R.narrative.compile(lines)), JSON.stringify(a));
assert.equal(R.narrative.plan(lines), a);
for (const text of ["Don't leave me", 'No te vayas', 'Never come back', 'Nunca vuelvas']) assert.equal(R.narrative.compile([{ text }])[0].action, null, text);
assert.equal(R.narrative.compile([{ text: 'Te espero en casa' }, { text: 'Te fuiste' }])[1].action, 'leave');
assert.equal(R.narrative.compile([{ text: '' }])[0], null);
assert.equal(R.narrative.compile([{ text: 'Goodbye' }, { text: "Don't leave me" }])[1].carry, null);
const chorus = R.narrative.compile(['I wait for you at home', 'A quiet moment', 'Goodbye on the street', 'A quiet moment', 'Still here'].map(text => ({ text })));
assert.equal(chorus[3].carry, 'wait'); assert.equal(chorus[3].place, 'cuarto');
assert.equal(chorus[4].carry, 'wait'); assert.equal(chorus[4].place, 'cuarto');
const changed = R.narrative.plan([{ text: 'We start again', t: 0 }]); assert.equal(changed[0].motif, 'semilla_brote');
console.log('ok: continuidad, acciones, estribillos, negación, caché e independencia del orden de reproducción');
